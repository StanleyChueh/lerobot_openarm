"""Recording recipe: where to record new real demos so every arena cell is within r of a real demo.

r  = the largest shift bin whose median distortion score is <= the strict threshold (from rendered v03 candidates).
Arena = grid cells where some attempt placed the can in view and on the table (placement in_view & on_table true).
Greedy k-center: real demo positions are fixed centres; add the arena cell farthest from every centre until all cells
are within r. Discrete modes (slots, object types, grasps, orientations) are not generated by sfagen and are listed
as a checklist: >= 2 real demos each.
usage: python tools/recording_plan.py <run_dir> <gen_work_dir> <out.md>
"""
import json, sys, glob
from pathlib import Path
import numpy as np


def radius(rows, strict, bin_cm=2.0):
    s = np.array([r['shift_cm'] for r in rows]); v = np.array([r['score'] for r in rows]); r = 0.0
    for lo in np.arange(0, s.max() + bin_cm, bin_cm):
        m = (s >= lo) & (s < lo + bin_cm)
        if m.sum() >= 3:
            if np.median(v[m]) > strict: break
            r = lo + bin_cm
    return r


def k_center(cells, centres, r):
    cells = np.asarray(cells, float); C = [np.asarray(c, float) for c in centres]; add = []
    d = np.min([np.linalg.norm(cells - c, axis=1) for c in C], axis=0) if C else np.full(len(cells), np.inf)
    while d.max() > r + 1e-9:
        i = int(d.argmax()); add.append(cells[i].tolist()); d = np.minimum(d, np.linalg.norm(cells - cells[i], axis=1))
    return add


def main(run, gen, out):
    run, gen = Path(run), Path(gen)
    sfagen = Path(__file__).resolve().parents[1]
    T = json.loads((sfagen / 'results/v03/thresholds.json').read_text())
    rows = [r for r in json.loads((sfagen / 'results/v03/selection.json').read_text())['rendered'] if r['family'] == 'object_workspace']
    r = radius(rows, T['strict'])
    grid = np.array(json.loads((run / 'grid.json').read_text())['positions_xy_m']) * 100; arena = set()
    for f in glob.glob(str(gen / 'candidates/ep*/checks.json')):
        for k, v in json.loads(Path(f).read_text()).items():
            p = v.get('placement') or {}
            if v.get('pass') or (p.get('in_view') and p.get('on_table')): arena.add(int(k.split('_')[2]))
    cells = grid[sorted(arena)]
    import yaml
    cfg = yaml.safe_load((sfagen / 'configs/openarm_pringles_v03.yaml').read_text())
    src = np.array(list(cfg['variations']['object_targets']['source_positions_xy_m'].values())) * 100
    add = k_center(cells, src, r) if r > 0 else cells.tolist()
    # Hole-based recipe (added after the pre-registered rule returned r = 12 cm because the score is ~flat in shift):
    # arena cells NOT covered by the strict selection must be within 4 cm (the strict calibration regime) of a new demo.
    cv = json.loads((sfagen / 'results/v03/coverage.json').read_text()); strict = set(cv['strict_targets'])
    holes = grid[[t for t in sorted(arena) if t not in strict]]
    hole_add = k_center(holes, [], 4.0) if len(holes) else []
    lines = [f"# Recording recipe (Pringles, generated by tools/recording_plan.py)\n",
             "## A. Hole-based recipe (recommended)",
             f"- {len(holes)} arena cells (in view and on the table) are not covered by the strict dataset: "
             + ', '.join(f'({h[0]:.0f}, {h[1]:.0f})' for h in holes),
             f"- **record {len(hole_add)} new can-start positions**, each covering holes within 4 cm (the shift regime the strict threshold was calibrated on); 2 demos per position recommended:\n",
             "| # | x (cm) | y (cm) |", "|---|---:|---:|"] + [f"| {i + 1} | {p[0]:.0f} | {p[1]:.0f} |" for i, p in enumerate(hole_add)] + [
             "\n## B. Pre-registered radius rule (reported, not recommended)"] + [
             f"- strict distortion threshold {T['strict']:.4f}; r = {r:.0f} cm (largest 2 cm shift bin with median score <= strict, >= 3 rendered candidates)",
             f"- arena: {len(cells)} grid cells (3 cm) where the can is in view and on the table; {len(src)} existing real demos",
             f"- record {len(add)} new can-start positions so every arena cell is within r of a real demo. "
             "The score barely depends on shift (visible rear-row ghosts are not reflected in its median), so r saturates; this rule is uninformative here.\n",
             "| # | x (cm) | y (cm) |", "|---|---:|---:|"] + [f"| {i + 1} | {p[0]:.0f} | {p[1]:.0f} |" for i, p in enumerate(add)] + [
             "\nCoordinates: robot world frame used by sfagen (x small = rear). Mark them on the table with the existing calibration.",
             "\n## Discrete modes: never synthesized, must be in the real demos (>= 2 each)",
             "- every insertion slot / target receptacle (battery: each slot)", "- each object type and grasp type",
             "- object orientations beyond the recorded ones (sfagen translates only)", "- each hand-over style if more than one is wanted"]
    Path(out).write_text('\n'.join(lines) + '\n'); print('\n'.join(lines[:12]))
    return r, add


if __name__ == '__main__':
    main(*sys.argv[1:4])
